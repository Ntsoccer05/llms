# =============================================================================
# マルチエージェントの基本パターン
# =============================================================================
# 複数のAIエージェントを連携させる基本的な方法を実装しています。
# 監督者エージェントが2つのサブエージェント（計算、俳句）を使いこなすパターンです。

from dotenv import load_dotenv
from strands import Agent, tool
from strands_tools import calculator

load_dotenv()

# =============================================================================
# サブエージェント1：計算専門のAI
# =============================================================================
# @tool デコレータ: 関数を「AIエージェントが使えるツール」に変換
@tool
def math_agent(query: str) -> str:
    """数学の計算を行うサブエージェント"""
    agent = Agent(
        model="us.anthropic.claude-3-7-sonnet-20250219-v1:0",
        system_prompt="ツールを使って計算を行ってください",
        tools=[calculator]  # 計算機能を提供
    )
    return str(agent(query))

# =============================================================================
# サブエージェント2：俳句専門のAI
# =============================================================================
@tool
def haiku_agent(query: str) -> str:
    """俳句を詠むサブエージェント"""
    agent = Agent(
        model="us.anthropic.claude-3-7-sonnet-20250219-v1:0",
        system_prompt="与えられたお題で五・七・五の俳句を詠んで"
    )
    return str(agent(query))

# =============================================================================
# 監督者エージェント
# =============================================================================
# 2つのサブエージェントを統括し、タスクを適切に振り分ける
orchestrator = Agent(
    model="us.anthropic.claude-3-7-sonnet-20250219-v1:0",
    system_prompt="与えられた問題を計算して、答えを俳句として詠んで",
    tools=[math_agent, haiku_agent]
)

# 実行
orchestrator("十円持っている太郎くんが二十円もらいました。今いくら？")